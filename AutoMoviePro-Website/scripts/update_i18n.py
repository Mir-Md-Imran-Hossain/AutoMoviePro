def main():
    target_path = 'assets/js/i18n-site.js'
    with open(target_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Iterate through each language and merge dictionaries
    for lang, new_dict in ADDITIONS.items():
        # Find where lang: { starts
        pattern = rf'(\b{lang}\s*:\s*\{{)'
        m = re.search(pattern, content)
        if not m:
            print(f"Error: {lang} block not found!")
            continue

        insert_pos = m.end()
        # Build JS string for new keys
        lines = []
        for k, v in new_dict.items():
            escaped_v = json.dumps(v, ensure_ascii=False)
            lines.append(f"      {k}: {escaped_v},")
        insert_text = "\n" + "\n".join(lines)
        content = content[:insert_pos] + insert_text + content[insert_pos:]

    # Remove any old duplicates where the same key might be redefined later in the same language block
    # Or cleaner: clean up any remaining Omni occurrences
    content = content.replace("Omni Video Content Studio", "Automovie Pro - Social Media Content Automation Engine")
    content = content.replace("Omni Video Studio", "Automovie Pro - Social Media Content Automation Engine")
    content = content.replace("Omni FB Business Manager", "Automovie Pro - FB Business Manager & Ad Automation Engine")
    content = content.replace("Omni FB Profile & Page Post", "Automovie Pro - FB Profile & Page Post Automation Engine")
    content = content.replace("Omni Profile & Page Post", "Automovie Pro - FB Profile & Page Post Automation Engine")
    content = content.replace("Omni", "Automovie Pro")

    with open(target_path, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Successfully updated assets/js/i18n-site.js")

if __name__ == '__main__':
    main()
