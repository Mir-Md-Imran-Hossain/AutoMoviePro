def get_dynamic_marketing_post():
    """
    Returns (post_text, banner_image_path) with strictly matched banner and content.
    Uses history-aware rotation to ensure ALL 7 templates cycle without repeating the same banner.
    Enforces 100% strict headline-to-banner pairing: AutoMovie banners NEVER get OmniSocial headlines.
    """
    history_file = r"E:\AI Assistant\Social Media Hub\Profiles\automovie_pro_page\history.json"
    recent_banners = []
    if os.path.exists(history_file):
        try:
            import json
            with open(history_file, "r", encoding="utf-8") as f:
                hist = json.load(f)
                recent_banners = [os.path.basename(entry.get("banner", "")) for entry in hist[-4:] if entry.get("banner")]
        except Exception:
            pass

    # Filter templates not used recently
    available_templates = [t for t in POST_TEMPLATES if t["banner"] not in recent_banners]
    if not available_templates:
        available_templates = POST_TEMPLATES

    selected_item = random.choice(available_templates)
    banner_file = selected_item["banner"]
    banner_path = os.path.join(BANNER_DIR, banner_file)
    
    # Strict headline alignment: Banner and Header MUST match 100%
    if "omnisocial" in banner_file.lower():
        header = random.choice(OMNISOCIAL_HEADERS)
    else:
        header = random.choice(AUTOMOVIE_HEADERS)
        
    outro = random.choice(OUTRO_VARIATIONS)
    ref_code = f"\n\n[অফিশিয়াল ভেরিফিকেশন কোড: #AMP-{random.randint(1000, 9999)}]"
    
    full_text = f"{header}\n\n{selected_item['body']}{outro}{ref_code}"
    return full_text, banner_path

