def get_dynamic_marketing_post(product_filter: str = None):
    """
    Returns (post_text, banner_image_path) with strictly matched banner and content.
    Optionally filters by specific product_id ('video_studio', 'fb_business', 'profile_page', 'wa_marketing', 'master').
    Uses history-aware rotation so templates cycle without repeating the same banner.
    Enforces 100% strict product-to-banner pairing with ZERO price confusion.
    Guarantees 1-click website and WhatsApp links at the TOP and throughout the copy.
    """
    history_file = r"E:\AI Assistant\Social Media Hub\Profiles\automovie_pro_page\history.json"
    recent_banners = []
    if os.path.exists(history_file):
        try:
            import json
            with open(history_file, "r", encoding="utf-8") as f:
                hist = json.load(f)
                recent_banners = [os.path.basename(entry.get("banner", "")) for entry in hist[-4:] if entry.get("banner")]
        except Exception:
            pass

    pool = POST_TEMPLATES
    if product_filter:
        filtered = [t for t in pool if t.get("product_id") == product_filter]
        if filtered:
            pool = filtered

    # Filter templates not used recently
    available_templates = [t for t in pool if t["banner"] not in recent_banners]
    if not available_templates:
        available_templates = pool

    selected_item = random.choice(available_templates)
    banner_file = selected_item["banner"]
    banner_path = os.path.join(BANNER_DIR, banner_file)

    cat = selected_item.get("category", "video_studio")
    header_list = CATEGORY_HEADERS.get(cat, CATEGORY_HEADERS["video_studio"])
    header = random.choice(header_list)

    top_cta = (
        "⚠️ [সার্ভার আপগ্রেড নোটিশ: আগামী ১ সপ্তাহ নতুন ব্যবহারকারী এন্ট্রি স্থগিত • ১ সপ্তাহ পর স্পেশাল রি-লঞ্চ অফার!]\n"
        "🌐 বিস্তারিত ফিচার ও ওয়েবসাইট: https://automoviepro.com\n"
        "💬 ১ সপ্তাহ পরের VIP Waitlist-এ নাম জমা দিন: https://wa.me/8801968111593"
    )

    outro = random.choice(OUTRO_VARIATIONS)
    ref_code = f"\n\n[অফিশিয়াল ভেরিফিকেশন কোড: #AMP-{random.randint(1000, 9999)}]"

    full_text = f"{header}\n\n{top_cta}\n\n{selected_item['body']}{outro}{ref_code}"
    return full_text, banner_path

