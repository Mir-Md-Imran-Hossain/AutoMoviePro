def test_stage_a_cross_check_fixes_bmw_car_blunder():
    source = {
        "topic": "BMW ফ্যাক্টরিতে Figure 02 আসলে কী করছে",
        "niche": "Tech & Robotics",
        "script_scenes": [
            {
                "shot_number": 1,
                "voiceover_script": "বিএমডব্লিউ কারখানায় শুরু হয়েছে রোবটের কর্মযজ্ঞ।",
            }
        ]
    }
    # Bad visual plan generated by naive LLM associating BMW with cars driving on road
    bad_plan = {
        "production_metadata": {},
        "render_scenes": [
            {
                "shot_number": 1,
                "visual_subject": "broll",
                "visual_prompt": "Cinematic shot of a sleek BMW car driving on highway at sunset, high speed",
                "render_type": "VIDEO",
            }
        ]
    }
    fixed_payload, audit = cross_check_visual_plan(bad_plan, source)
    fixed_shot = fixed_payload["render_scenes"][0]
    
    # Verify the mismatch was detected and repaired
    assert audit["total_mismatches_fixed"] > 0
    assert "automotive manufacturing plant" in fixed_shot["visual_prompt"]
    assert "highway" not in fixed_shot["visual_prompt"].lower()
    assert "driving" not in fixed_shot["visual_prompt"].lower()
    assert fixed_shot["thematic_domain"] == "Industrial Robotics & Automotive Factory Automation"


