def test_macro_analysis_bmw_robotics():
    source = {
        "topic": "BMW ফ্যাক্টরিতে Figure 02 আসলে কী করছে",
        "niche": "Tech & Robotics",
        "script_scenes": [
            {
                "shot_number": 1,
                "voiceover_script": "বিএমডব্লিউ এর স্পার্টানবার্গ কারখানায় মানুষের মতো কাজ করছে ফিগার ০২ রোবট!",
            }
        ]
    }
    ctx = analyze_macro_topic_and_script(source)
    assert ctx.visual_domain == "Industrial Robotics & Automotive Factory Automation"
    assert "automotive manufacturing plant" in ctx.primary_setting
    assert any("humanoid robot" in e for e in ctx.primary_entities)
    assert any("commercial car driving" in f for f in ctx.forbidden_tangents)
    assert ctx.face_policy == "strictly_forbidden"


