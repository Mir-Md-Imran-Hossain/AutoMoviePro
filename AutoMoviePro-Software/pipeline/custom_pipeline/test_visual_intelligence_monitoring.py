def test_stage_b_prompt_clearance_gate():
    scene = {
        "shot_number": 1,
        "thematic_domain": "Industrial Robotics & Automotive Factory Automation",
        "topic": "BMW ফ্যাক্টরিতে Figure 02 আসলে কী করছে",
        "niche": "Tech & Robotics",
    }
    # Raw prompt with a leaked forbidden tangent and missing silent video directive
    raw_prompt = "Cinematic video of Figure 02 humanoid robot inside BMW factory with commercial car driving on highway"
    narration = "কারখানায় রোবট সফলভাবে বিভিন্ন যন্ত্রাংশ তুলছে।"

    clearance = audit_prompt_preflight_clearance(scene, raw_prompt, narration, for_video=True)
    assert clearance["passed"] is True
    assert clearance["clearance"] in ("GRANTED", "REPAIRED_AND_GRANTED")
    assert "SILENT VIDEO ONLY" in clearance["verified_prompt"]
    assert "commercial car driving on highway" not in clearance["verified_prompt"]


def test_stock_search_query_anchors_to_macro_domain():
    # BMW robotics scene: stock query must be factory robot automation, NOT cars
    bmw_scene = {
        "shot_number": 1,
        "thematic_domain": "Industrial Robotics & Automotive Factory Automation",
        "topic": "BMW ফ্যাক্টরিতে Figure 02 আসলে কী করছে",
        "voiceover_script": "বিএমডব্লিউ এর নতুন রোবট ট্রায়াল শুরু হয়েছে।",
    }
    query = stock_search_query(bmw_scene)
    assert "industrial factory robot" in query.lower() or "robot" in query.lower()
    assert "car" not in query.lower().split()
    assert "motorcycle" not in query.lower().split()

    # Deep sea scene: stock query must be ocean underwater floor, NOT mountain
    sea_scene = {
        "shot_number": 1,
        "thematic_domain": "Deep Sea Oceanography & Abyssal Benthic Geochemistry",
        "topic": "৪০০০ মিটার গভীরে সমুদ্র নিজেই অক্সিজেন বানাচ্ছে!",
        "voiceover_script": "সমুদ্রের তলদেশের শিলা ও অক্সিজেন।",
    }
    sea_query = stock_search_query(sea_scene)
    assert "deep sea" in sea_query.lower() or "underwater" in sea_query.lower() or "ocean" in sea_query.lower()
    assert "mountain" not in sea_query.lower()
    assert "beach" not in sea_query.lower()
