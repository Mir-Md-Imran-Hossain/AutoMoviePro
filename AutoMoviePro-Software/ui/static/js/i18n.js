window.ampT = function ampT(key) {
  const lang = localStorage.getItem("amp_ui_lang") || "bn";
  const pack = window.AMP_I18N[lang] || window.AMP_I18N.bn;
  return pack[key] || window.AMP_I18N.en[key] || key;
};

window.ampApplyI18n = function ampApplyI18n() {
  const lang = localStorage.getItem("amp_ui_lang") || "bn";
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const val = window.ampT(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
      else if (el.type !== "password" && el.type !== "file" && el.type !== "time") {
        /* skip value overwrite for inputs */
      }
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = window.ampT(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = window.ampT(el.getAttribute("data-i18n-title"));
  });
  const sel = document.getElementById("uiLangSelect");
  if (sel) sel.value = lang;
  // Niche dropdown labels/blurbs follow UI language
  if (typeof window.loadNiches === "function") {
    try { window.loadNiches(); } catch (e) { /* ignore */ }
  }
};

window.ampInitUiLangSelect = function ampInitUiLangSelect() {
  const sel = document.getElementById("uiLangSelect");
  if (!sel || sel.dataset.ampBound === "1") return;
  sel.dataset.ampBound = "1";
  sel.innerHTML = (window.AMP_UI_LANGS || [])
    .map((l) => `<option value="${l.code}">${l.name}</option>`)
    .join("");
  const cur = localStorage.getItem("amp_ui_lang") || "bn";
  sel.value = cur;
  sel.addEventListener("change", () => {
    localStorage.setItem("amp_ui_lang", sel.value || "bn");
    window.ampApplyI18n();
  });
};

document.addEventListener("DOMContentLoaded", () => {
  try {
    window.ampInitUiLangSelect();
    window.ampApplyI18n();
  } catch (e) { /* ignore */ }
});
